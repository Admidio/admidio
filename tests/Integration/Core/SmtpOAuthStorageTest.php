<?php
/**
 * What sending with OAuth 2.0 needs from the database: secrets that are stored exactly as they
 * were entered, and a refresh that holds the row of the refresh token while it runs.
 *
 * The unit tests replace the preferences with a stand-in; these ones use the real SettingsManager,
 * the Preferences entity behind it and a second connection to the test database.
 */

namespace Admidio\Tests\Integration\Core;

use Admidio\Infrastructure\SmtpOAuth;
use Admidio\Infrastructure\Utils\StringUtils;
use Admidio\Organizations\Entity\Organization;
use Admidio\Tests\Support\AdmidioTestFixture;
use Admidio\Tests\Support\DatabaseTestCase;
use PDO;
use PDOException;

class SmtpOAuthStorageTest extends DatabaseTestCase
{
    private const SECRET = 'a<b>c&amp;d"e\'f</script>';

    /**
     * A client secret is generated by the provider and may contain any character. The entity would
     * remove what looks like HTML and decode entities, which changes the secret, so the token
     * endpoint would answer invalid_client.
     */
    public function testAClientSecretIsStoredExactlyAsEntered(): void
    {
        $organization = (new AdmidioTestFixture($this->getDatabase()))->createAndSaveOrganization('SecretOrg', 'secret');
        $settings = (new Organization($this->getDatabase(), $organization['org_id']))->getSettingsManager();

        $settings->set('mail_smtp_oauth_client_secret', self::SECRET);
        $settings->set('mail_sender_name', 'Choir <b>Alto</b>');

        $reloaded = (new Organization($this->getDatabase(), $organization['org_id']))->getSettingsManager();
        $this->assertSame(self::SECRET, $reloaded->getString('mail_smtp_oauth_client_secret'));
        $this->assertSame('Choir Alto', $reloaded->getString('mail_sender_name'), 'other preferences are still freed from HTML');
    }

    /** The global filter of the request parameters leaves the secret alone as well. */
    public function testTheRequestFilterKeepsTheClientSecret(): void
    {
        $filtered = StringUtils::strStripSpecialTags(array('mail_smtp_oauth_client_secret' => self::SECRET, 'mail_sender_name' => '<b>Choir</b>'));

        $this->assertSame(self::SECRET, $filtered['mail_smtp_oauth_client_secret']);
        $this->assertSame('Choir', $filtered['mail_sender_name']);
    }

    /**
     * While one process refreshes, another one must not read the same refresh token: with Microsoft's
     * rotation, the one that stores last would store the older answer. A second connection that asks
     * for the row without waiting is refused while the refresh runs.
     */
    public function testTheRefreshHoldsTheRowOfTheRefreshToken(): void
    {
        $organizationId = (int)$this->getDatabase()->queryPrepared(
            'SELECT MIN(prf_org_id) FROM ' . TBL_PREFERENCES . ' WHERE prf_name = ?',
            array('mail_smtp_oauth_refresh_token')
        )->fetchColumn();
        $this->assertGreaterThan(0, $organizationId, 'the installation seeds the preference into its organization');
        $settings = (new Organization($this->getDatabase(), $organizationId))->getSettingsManager();
        $other = $this->secondConnection();

        $oauth = new class ($settings) extends SmtpOAuth {
            public function underLock(callable $refresh): array
            {
                return $this->lockRefreshToken($refresh);
            }
        };
        $lockedDuringRefresh = $oauth->underLock(fn (string $refreshToken): array => array('locked' => $this->rowIsLocked($other, $organizationId)));

        $this->assertTrue($lockedDuringRefresh['locked']);
    }

    private function rowIsLocked(PDO $connection, int $organizationId): bool
    {
        $connection->beginTransaction();
        try {
            $statement = $connection->prepare(
                'SELECT prf_value FROM ' . TBL_PREFERENCES . ' WHERE prf_org_id = ? AND prf_name = ? FOR UPDATE NOWAIT'
            );
            $statement->execute(array($organizationId, 'mail_smtp_oauth_refresh_token'));
            return false;
        } catch (PDOException) {
            return true;
        } finally {
            $connection->rollBack();
        }
    }

    private function secondConnection(): PDO
    {
        $config = admidioTestDatabaseConfig();
        $dsn = $config['engine'] === 'postgres'
            ? 'pgsql:host=' . $config['host'] . ';port=' . $config['port'] . ';dbname=' . $config['database']
            : 'mysql:host=' . $config['host'] . ';port=' . $config['port'] . ';dbname=' . $config['database'] . ';charset=utf8mb4';

        return new PDO($dsn, $config['user'], $config['password'], array(PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION));
    }
}
